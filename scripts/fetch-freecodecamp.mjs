#!/usr/bin/env node
// Snapshots the owner's freeCodeCamp public profile into src/lib/freecodecamp.ts.
//
// The freeCodeCamp API only allows requests from https://www.freecodecamp.org, so the
// portfolio cannot read it from the browser and does not run a Worker to proxy it. The
// snapshot is baked at build time instead, the same way the footer year is.
import { syncSnapshot } from './lib/snapshot.mjs';

const USERNAME = 'yourin';
const API = `https://api.freecodecamp.org/users/get-public-profile?username=${USERNAME}`;

const toDay = (unixSeconds) => new Date(unixSeconds * 1000).toISOString().slice(0, 10);

async function fetchProfile() {
  const response = await fetch(API, { headers: { accept: 'application/json' } });
  if (!response.ok) throw new Error(`request failed with ${response.status} ${response.statusText}`);
  const payload = await response.json();
  const user = payload?.entities?.user?.[USERNAME];
  if (!user) throw new Error(`profile "${USERNAME}" was not found`);
  return user;
}

// The calendar is keyed by per-challenge timestamps, so several entries can share a day.
// The API ships raw counts only, so the 0-4 intensity is derived from the busiest day.
function toIntensity(user) {
  const counts = new Map();
  for (const [timestamp, count] of Object.entries(user.calendar ?? {})) {
    const key = toDay(Number(timestamp));
    counts.set(key, (counts.get(key) ?? 0) + Number(count));
  }
  const busiest = Math.max(1, ...counts.values());
  const intensity = {};
  for (const [key, count] of [...counts.entries()].sort()) {
    intensity[key] = Math.min(4, Math.ceil((count / busiest) * 4));
  }
  return { intensity, activeDays: counts.size };
}

function render(snapshot) {
  return `// Generated by scripts/fetch-freecodecamp.mjs — refresh with \`bun run freecodecamp:sync\`.
// The freeCodeCamp API is CORS-locked to freecodecamp.org, so the portfolio bakes this
// snapshot at build time rather than fetching it in the browser.
export type FreeCodeCampProfile = {
  username: string;
  points: number;
  /** Solved-challenge intensity per UTC day (0-4), keyed by \`YYYY-MM-DD\`; quiet days are omitted. */
  calendar: Record<string, number>;
  /** Build-time stamp that anchors the activity graph and the "last updated" label. */
  syncedAt: string;
};

export const freeCodeCamp: FreeCodeCampProfile = ${JSON.stringify(snapshot, null, 2)};
`;
}

await syncSnapshot({
  label: 'freeCodeCamp',
  file: 'src/lib/freecodecamp.ts',
  generate: async () => {
    const profile = await fetchProfile();
    const { intensity, activeDays } = toIntensity(profile);
    const snapshot = {
      username: profile.username ?? USERNAME,
      points: profile.points ?? 0,
      calendar: intensity,
      syncedAt: new Date().toISOString(),
    };
    return {
      source: render(snapshot),
      summary: `snapshotted ${activeDays} active days and ${snapshot.points} points into src/lib/freecodecamp.ts`,
    };
  },
});
