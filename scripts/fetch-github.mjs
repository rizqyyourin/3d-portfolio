#!/usr/bin/env node
// Snapshots the owner's GitHub contribution calendar into src/lib/github.ts.
//
// GitHub's GraphQL API needs a token, so this reads the public contribution calendar
// fragment that github.com/users/<name>/contributions renders. Like the freeCodeCamp
// snapshot, it is baked at build time because the site has no Worker to proxy it.
import { syncSnapshot } from './lib/snapshot.mjs';

const USERNAME = 'rizqyyourin';

async function fetchContributions() {
  const year = new Date().getUTCFullYear();
  const url = `https://github.com/users/${USERNAME}/contributions?from=${year}-01-01&to=${year}-12-31`;
  const response = await fetch(url, {
    headers: { accept: 'text/html', 'user-agent': `yourin-portfolio-build (+https://yourin.my.id)` },
  });
  if (!response.ok) throw new Error(`request failed with ${response.status} ${response.statusText}`);
  const html = await response.text();

  const summary = html.match(/([\d,]+)\s+contributions?\s+in\s+(\d{4})/);
  const cells = [...html.matchAll(/<td[^>]*class="[^"]*ContributionCalendar-day[^"]*"[^>]*>/g)].map(match => match[0]);
  if (!summary || cells.length === 0) throw new Error('the contribution calendar was not found');

  // GitHub already labels each day 0-4, so that intensity is kept as-is. Quiet days are
  // dropped: the graph fills them in from the date range it renders.
  const intensity = {};
  for (const cell of cells) {
    const date = cell.match(/data-date="(\d{4}-\d{2}-\d{2})"/)?.[1];
    const level = Number(cell.match(/data-level="(\d)"/)?.[1] ?? 0);
    if (date && level > 0) intensity[date] = level;
  }

  return {
    contributions: Number(summary[1].replace(/,/g, '')),
    year: Number(summary[2]),
    intensity: Object.fromEntries(Object.entries(intensity).sort()),
    activeDays: Object.keys(intensity).length,
  };
}

function render(snapshot) {
  return `// Generated by scripts/fetch-github.mjs — refresh with \`bun run github:sync\`.
// GitHub's GraphQL API needs a token, so the portfolio bakes this snapshot of the public
// contribution calendar at build time rather than fetching it in the browser.
export type GitHubContributions = {
  username: string;
  /** Contributions counted for the calendar year, as GitHub reports them. */
  contributions: number;
  year: number;
  /** Contribution intensity per UTC day (0-4), keyed by \`YYYY-MM-DD\`; quiet days are omitted. */
  calendar: Record<string, number>;
  /** Build-time stamp that anchors the activity graph and the "last updated" label. */
  syncedAt: string;
};

export const githubContributions: GitHubContributions = ${JSON.stringify(snapshot, null, 2)};
`;
}

await syncSnapshot({
  label: 'GitHub',
  file: 'src/lib/github.ts',
  generate: async () => {
    const { contributions, year, intensity, activeDays } = await fetchContributions();
    const snapshot = {
      username: USERNAME,
      contributions,
      year,
      calendar: intensity,
      syncedAt: new Date().toISOString(),
    };
    return {
      source: render(snapshot),
      summary: `snapshotted ${contributions} contributions across ${activeDays} active days in ${year} into src/lib/github.ts`,
    };
  },
});
